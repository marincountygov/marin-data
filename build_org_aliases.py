#!/usr/bin/env python3
"""Write organizations/aliases.json: other names for each organization, and the official name each one means.

Built from the name and alternateName of every organization in output/organizations.jsonld. An alias that
could mean two different organizations is not given a meaning. It is listed under ambiguous instead, so an
app can ask a person rather than guess. Marin Reach copies this file. Do not edit it by hand.

  python3 build_org_aliases.py           write organizations/aliases.json
  python3 build_org_aliases.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "aliases.json"
graph = json.loads((ROOT / "output" / "organizations.jsonld").read_text())["@graph"]

owners = {}
for o in graph:
    for label in [o["name"]] + o.get("alternateName", []):
        owners.setdefault(label.strip().casefold(), set()).add((o["name"], o["@id"]))

aliases, ambiguous = {}, {}
official = {o["name"].strip().casefold() for o in graph}
for o in graph:
    for alt in o.get("alternateName", []):
        key = alt.strip().casefold()
        if len(owners[key]) > 1:
            ambiguous[alt.strip()] = sorted(i for _, i in owners[key])
        elif key not in official:
            aliases[alt.strip()] = o["name"]
# A name two organizations share is ambiguous even when it is the official name of both.
for key, who in owners.items():
    if len(who) > 1:
        ambiguous.setdefault(next(n for n, _ in who), sorted(i for _, i in who))

doc = {
    "schemaVersion": "1.0.0",
    "title": "Other names for County of Marin organizations",
    "generated": "Generated by build_org_aliases.py from output/organizations.jsonld. Do not edit.",
    "aliases": dict(sorted(aliases.items(), key=lambda kv: kv[0].casefold())),
    "officialNames": sorted({o["name"] for o in graph}),
    "ambiguous": dict(sorted(ambiguous.items())),
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/aliases.json is out of date. Run: python3 build_org_aliases.py")
    print(f"ok: organizations/aliases.json is current ({len(aliases)} aliases, {len(ambiguous)} ambiguous)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(aliases)} aliases, {len(ambiguous)} ambiguous")
