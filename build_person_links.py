#!/usr/bin/env python3
"""Write organizations/people.json: which person each Marin Mentions monitor is about, and the seat they hold.

The link lives on the person, as the identifier local:marin-mentions-monitor-id in output/people.jsonld. The
seat comes from the person's role and its post (output/roles.jsonld, output/posts.jsonld): the role name, and the
district the post represents, shown as the name an app uses for the place (organizations/place-aliases.json).
marin-mentions copies this file. Do not edit it by hand.

  python3 build_person_links.py           write organizations/people.json
  python3 build_person_links.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "people.json"
out = ROOT / "output"
people = json.loads((out / "people.jsonld").read_text())["@graph"]
roles = json.loads((out / "roles.jsonld").read_text())["@graph"]
posts = {p["@id"]: p for p in json.loads((out / "posts.jsonld").read_text())["@graph"]}
labels = {v: k for k, v in json.loads((ROOT / "organizations" / "place-aliases.json").read_text())["labels"].items()}
others = set()
for f in ("monitors.json", "places.json", "events.json"):
    doc = json.loads((ROOT / "organizations" / f).read_text())
    others |= {r["monitorId"] for key in ("monitors", "places", "facilities", "events") for r in doc.get(key, [])}

rows = []
for person in people:
    for i in person.get("identifier", []):
        if i.get("propertyID") != "local:marin-mentions-monitor-id":
            continue
        seats = [r for r in roles if r["member"]["@id"] == person["@id"]]
        row = {"monitorId": i["value"], "code": next((c["value"] for c in person["identifier"] if c["propertyID"] == "gs:local"), None), "person": person["@id"], "name": person["name"], "label": person["name"]}
        if seats:
            seat = seats[0]
            row["role"] = seat["roleName"].split(",")[0]
            post = posts.get(seat.get("post", {}).get("@id"))
            district = post and post.get("representsJurisdiction")
            if district:
                row["district"] = labels[district["@id"]]
        rows.append(row)
rows.sort(key=lambda r: r["monitorId"])
ids = [r["monitorId"] for r in rows]
if len(ids) != len(set(ids)):
    sys.exit("a monitor id is on two people")
clash = set(ids) & others
if clash:
    sys.exit(f"monitor ids linked to a person and also to an organization, place, facility or event: {sorted(clash)}")
doc = {
    "schemaVersion": "1.0.0",
    "title": "Marin Mentions monitors and the people they are about",
    "generated": "Generated by build_person_links.py from output/people.jsonld, roles.jsonld and posts.jsonld. Do not edit.",
    "people": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/people.json is out of date. Run: python3 build_person_links.py")
    print(f"ok: organizations/people.json is current ({len(rows)} people)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} people")
