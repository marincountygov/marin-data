#!/usr/bin/env python3
"""Write organizations/locations.json: the places and facilities people can name in a tracked link.

Built from output/jurisdictions.jsonld (every place except the county itself) and output/facilities.jsonld.
The code of each is its own code, the gs:local identifier (see place_lib.py), and is not tied to any app. A code
is permanent: it ends up inside links people have already shared, so check_locations.py --against fails if
one is removed or changed. The label is what people see, and may change. Marin Links copies this file. Do not
edit it by hand.

  python3 build_location_list.py           write organizations/locations.json
  python3 build_location_list.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

import place_lib as lib

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "locations.json"
labels = json.loads((ROOT / "organizations" / "place-aliases.json").read_text())["labels"]
label_of = {jurisdiction: label for label, jurisdiction in labels.items()}
kinds = json.loads((ROOT / "organizations" / "place-kinds.json").read_text())["kinds"]

rows = []
for j in lib.graph("jurisdictions"):
    kind = lib.kind_of(j)
    if kind != "county":
        rows.append({"code": lib.code_of(j), "label": label_of[j["@id"]], "kind": kind, "id": j["@id"]})
rows += [{"code": lib.code_of(f), "label": f["name"], "kind": "facility", "id": f["@id"]} for f in lib.graph("facilities")]
errors = [f"{r['label']}: needs a code, a gs:local identifier" for r in rows if not r["code"]]
errors += [f"{r['code']}: a code is lowercase words with hyphens" for r in rows if r["code"] and not lib.CODE.match(r["code"])]
codes = [r["code"] for r in rows]
errors += [f"{c}: this code is used twice" for c in sorted({c for c in codes if codes.count(c) > 1})]
shown = [r["label"].casefold() for r in rows]
errors += [f"{l!r}: two locations have this label" for l in sorted({l for l in shown if shown.count(l) > 1})]
if errors:
    sys.exit("\n".join(errors))
rows.sort(key=lambda r: (r["label"].casefold(), r["code"]))
doc = {
    "schemaVersion": "1.0.0",
    "title": "Places and facilities that can be named in a tracked link",
    "generated": "Generated by build_location_list.py from output/jurisdictions.jsonld and output/facilities.jsonld. Do not edit.",
    "kinds": kinds,
    "locations": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/locations.json is out of date. Run: python3 build_location_list.py")
    print(f"ok: organizations/locations.json is current ({len(rows)} locations)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} locations")
