#!/usr/bin/env python3
"""Write organizations/locations.json: the places and sites people can name in a tracked link.

Built from output/jurisdictions.jsonld (every place except the county itself) and output/facilities.jsonld.
A place's code is its Marin Mentions monitor id (san-rafael, marin-district-3, bolinas). A facility's code is the
last part of its id (civic-center). A code is permanent: it ends up inside links people have already shared, so
check_locations.py --against fails if one is removed or changed. The label is what people see, and may change.
Marin Links copies this file. Do not edit it by hand.

  python3 build_location_list.py           write organizations/locations.json
  python3 build_location_list.py --check   fail if the file is out of date
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "locations.json"
CODE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
places_doc = json.loads((ROOT / "organizations" / "places.json").read_text())
places = places_doc["places"]
facilities = json.loads((ROOT / "organizations" / "facilities.json").read_text())["facilities"]

rows = [{"code": p["monitorId"], "label": p["label"], "kind": p["kind"], "id": p["jurisdiction"]} for p in places]
rows += [{"code": f["id"].rsplit("/", 1)[1], "label": f["name"], "kind": "facility", "id": f["id"]} for f in facilities]
errors = [f"{r['code']}: a code is lowercase words with hyphens" for r in rows if not CODE.match(r["code"])]
codes = [r["code"] for r in rows]
errors += [f"{c}: this code is used twice" for c in sorted({c for c in codes if codes.count(c) > 1})]
shown = [r["label"].casefold() for r in rows]
errors += [f"{l!r}: two locations have this label" for l in sorted({l for l in shown if shown.count(l) > 1})]
if errors:
    sys.exit("\n".join(errors))
rows.sort(key=lambda r: (r["label"].casefold(), r["code"]))
doc = {
    "schemaVersion": "1.0.0",
    "title": "Places and sites that can be named in a tracked link",
    "generated": "Generated by build_location_list.py from output/jurisdictions.jsonld and output/facilities.jsonld. Do not edit.",
    "kinds": places_doc["kinds"],
    "locations": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/locations.json is out of date. Run: python3 build_location_list.py")
    print(f"ok: organizations/locations.json is current ({len(rows)} locations)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} locations")
