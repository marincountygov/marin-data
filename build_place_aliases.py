#!/usr/bin/env python3
"""Write organizations/place-aliases.json: other names for each place, and the name an app shows for it.

Built from the name and alternateName of every jurisdiction in output/jurisdictions.jsonld. The name an
app shows (the label) is the place's name, except for a supervisorial district, which is shown as
"District N". An alias that could mean two different places is not given a meaning. It is listed under
ambiguous instead, so an app can ask a person rather than guess. Marin Reach copies this file. Do not edit
it by hand.

  python3 build_place_aliases.py           write organizations/place-aliases.json
  python3 build_place_aliases.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "place-aliases.json"
graph = json.loads((ROOT / "output" / "jurisdictions.jsonld").read_text())["@graph"]


def label(j):
    for i in j.get("identifier", []):
        if i.get("propertyID") == "local:marin-supervisorial-district":
            return f"District {i['value']}"
    return j["name"]


owners = {}  # lowercase name -> {(label, @id)}
for j in graph:
    for name in [j["name"], label(j)] + j.get("alternateName", []):
        owners.setdefault(name.strip().casefold(), set()).add((label(j), j["@id"]))

aliases, ambiguous = {}, {}
labels = {label(j) for j in graph}
for j in graph:
    for name in [j["name"]] + j.get("alternateName", []):
        key = name.strip().casefold()
        if len(owners[key]) > 1:
            ambiguous[name.strip()] = sorted(i for _, i in owners[key])
        elif name.strip() != label(j):
            aliases[name.strip()] = label(j)

doc = {
    "schemaVersion": "1.0.0",
    "title": "Other names for places in Marin County",
    "generated": "Generated by build_place_aliases.py from output/jurisdictions.jsonld. Do not edit.",
    "aliases": dict(sorted(aliases.items(), key=lambda kv: kv[0].casefold())),
    "labels": {label(j): j["@id"] for j in sorted(graph, key=lambda j: label(j).casefold())},
    "ambiguous": dict(sorted(ambiguous.items())),
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/place-aliases.json is out of date. Run: python3 build_place_aliases.py")
    print(f"ok: organizations/place-aliases.json is current ({len(aliases)} aliases, {len(ambiguous)} ambiguous)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(aliases)} aliases, {len(ambiguous)} ambiguous")
