#!/usr/bin/env python3
"""Write organizations/events.json: which event each Marin Mentions monitor is about.

The link lives on the event, as the identifier local:marin-mentions-monitor-id in
output/events.jsonld. This file is generated from it for apps that cannot read JSON-LD
easily. marin-mentions copies it. Do not edit it by hand.

  python3 build_event_links.py           write organizations/events.json
  python3 build_event_links.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "events.json"
graph = json.loads((ROOT / "output" / "events.jsonld").read_text())["@graph"]
others = set()
for f in ("monitors.json", "places.json"):
    doc = json.loads((ROOT / "organizations" / f).read_text())
    others |= {r["monitorId"] for key in ("monitors", "places", "facilities") for r in doc.get(key, [])}

rows = sorted(
    ({"monitorId": i["value"], "event": o["@id"], "name": o["name"]}
     for o in graph for i in o.get("identifier", []) if i.get("propertyID") == "local:marin-mentions-monitor-id"),
    key=lambda r: r["monitorId"],
)
ids = [r["monitorId"] for r in rows]
if len(ids) != len(set(ids)):
    sys.exit("a monitor id is on two events")
clash = set(ids) & others
if clash:
    sys.exit(f"monitor ids linked to an event and also to an organization, place or facility: {sorted(clash)}")
doc = {
    "schemaVersion": "1.0.0",
    "title": "Marin Mentions monitors and the events they are about",
    "generated": "Generated by build_event_links.py from output/events.jsonld. Do not edit.",
    "events": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/events.json is out of date. Run: python3 build_event_links.py")
    print(f"ok: organizations/events.json is current ({len(rows)} events)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} events")
