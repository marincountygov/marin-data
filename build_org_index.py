#!/usr/bin/env python3
"""Write organizations/index.json: a short list of every organization, for apps that only need to look one up.

Each entry has the organization's @id, its name, its other names, its type and its parent. An app can check that
an organization it names exists, and that the name it shows is the official name or one of the other names.
Built from output/organizations.jsonld. Do not edit by hand.

  python3 build_org_index.py           write organizations/index.json
  python3 build_org_index.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "index.json"
graph = json.loads((ROOT / "output" / "organizations.jsonld").read_text())["@graph"]

rows = []
for o in graph:
    rows.append({
        "id": o["@id"],
        "name": o["name"],
        "alternateName": sorted(o.get("alternateName", [])),
        "type": o.get("organizationClassification"),
        "parent": (o.get("parentOrganization") or {}).get("@id"),
    })
rows.sort(key=lambda r: r["id"])
ids = [r["id"] for r in rows]
if len(ids) != len(set(ids)):
    sys.exit("an organization @id appears twice")
doc = {
    "schemaVersion": "1.0.0",
    "title": "County of Marin organizations: a short list for looking one up",
    "generated": "Generated by build_org_index.py from output/organizations.jsonld. Do not edit.",
    "organizations": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/index.json is out of date. Run: python3 build_org_index.py")
    print(f"ok: organizations/index.json is current ({len(rows)} organizations)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} organizations")
