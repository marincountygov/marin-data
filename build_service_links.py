#!/usr/bin/env python3
"""Write organizations/services.json: which service each Marin Mentions monitor is about, and how to search for it.

The link lives on the service, as the identifier local:marin-mentions-monitor-id in output/services.jsonld. This
file is generated from it, with the names and search hints (see place_lib.py). marin-mentions copies it. Do not
edit it by hand.

  python3 build_service_links.py           write organizations/services.json
  python3 build_service_links.py   --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

import place_lib as lib

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "services.json"
graph = lib.graph("services")
SEARCH_NAME = True  # a service is searched by its own name

rows = sorted(
    ({"monitorId": m, "code": lib.code_of(o), "service": o["@id"], "name": o["name"], "label": o["name"], "kind": "service",
      **({} if SEARCH_NAME else {"searchName": False}), **lib.search_of(o)}
     for o in graph if o["@type"] != "DefinedTermSet" for m in lib.ident(o, lib.MONITOR_ID)),
    key=lambda r: r["monitorId"],
)
ids = [r["monitorId"] for r in rows]
if len(ids) != len(set(ids)):
    sys.exit("a monitor id is on two services")
doc = {
    "schemaVersion": "1.0.0",
    "title": "Marin Mentions monitors and the services they are about",
    "generated": "Generated by build_service_links.py from output/services.jsonld. Do not edit.",
    "services": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/services.json is out of date. Run: python3 build_service_links.py")
    print(f"ok: organizations/services.json is current ({len(rows)} services)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} services")
