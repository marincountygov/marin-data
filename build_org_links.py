#!/usr/bin/env python3
"""Write organizations/monitors.json: which organization each Marin Mentions monitor is about.

The link lives on the organization, as the identifier local:marin-mentions-monitor-id in
output/organizations.jsonld. This file is generated from it for apps that cannot read JSON-LD
easily. marin-mentions copies it. Do not edit it by hand.

  python3 build_org_links.py           write organizations/monitors.json
  python3 build_org_links.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "monitors.json"
graph = json.loads((ROOT / "output" / "organizations.jsonld").read_text())["@graph"]
not_orgs = json.loads((ROOT / "organizations" / "monitors-not-organizations.json").read_text())["monitors"]


def ident(o, prop):
    return [i["value"] for i in o.get("identifier", []) if i.get("propertyID") == prop]


rows = []
for o in graph:
    for monitor_id in ident(o, "local:marin-mentions-monitor-id"):
        agency = ident(o, "local:marin-links-agency-id")
        rows.append({
            "monitorId": monitor_id,
            "organization": o["@id"],
            "name": o["name"],
            "type": o.get("organizationClassification"),
            "agencyId": agency[0] if agency else None,
        })
rows.sort(key=lambda r: r["monitorId"])
ids = [r["monitorId"] for r in rows]
if len(ids) != len(set(ids)):
    sys.exit("a monitor id is on two organizations")
both = set(ids) & {n["monitorId"] for n in not_orgs}
if both:
    sys.exit(f"monitor ids both linked to an organization and listed as not organizations: {sorted(both)}")
doc = {
    "schemaVersion": "1.0.0",
    "title": "Marin Mentions monitors and the organizations they are about",
    "generated": "Generated by build_org_links.py from output/organizations.jsonld. Do not edit.",
    "monitors": rows,
    "notOrganizations": not_orgs,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/monitors.json is out of date. Run: python3 build_org_links.py")
    print(f"ok: organizations/monitors.json is current ({len(rows)} monitors)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} monitors, {len(not_orgs)} not organizations")
