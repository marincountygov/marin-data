#!/usr/bin/env python3
"""Write organizations/facilities.json: every facility, with the details an app needs to show or map it.

Built from output/facilities.jsonld. Each facility says who runs it, as operator: government,
nongovernment, unknown (not yet confirmed) or notApplicable (a natural feature). A facility with a
local:marin-mentions-monitor-id also carries monitorId. Marin Reach copies this file to name and place
its venues. Do not edit it by hand.

  python3 build_facility_list.py           write organizations/facilities.json
  python3 build_facility_list.py --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "facilities.json"
graph = json.loads((ROOT / "output" / "facilities.jsonld").read_text())["@graph"]
OPERATORS = {"government", "nongovernment", "unknown", "notApplicable"}
ADDRESS = {"streetAddress": "streetAddress", "addressLocality": "locality", "addressRegion": "region",
           "postalCode": "postalCode", "addressCountry": "country"}


def ident(o, prop):
    return [i["value"] for i in o.get("identifier", []) if i.get("propertyID") == prop]


def prop(o, name):
    return [p["value"] for p in o.get("additionalProperty", []) if p.get("propertyID") == name]


rows, errors = [], []
for o in graph:
    operator = prop(o, "local:operator-type")
    if len(operator) != 1 or operator[0] not in OPERATORS:
        errors.append(f"{o['name']}: needs exactly one local:operator-type, one of {sorted(OPERATORS)}")
        continue
    row = {"id": o["@id"], "name": o["name"], "type": o["@type"], "operator": operator[0]}
    if o.get("alternateName"):
        row["alternateNames"] = o["alternateName"]
    monitor = ident(o, "local:marin-mentions-monitor-id")
    if monitor:
        row["monitorId"] = monitor[0]
    if o.get("address"):
        row["address"] = {out: o["address"][src] for src, out in ADDRESS.items() if o["address"].get(src)}
    if o.get("geo"):
        row["geo"] = {"latitude": o["geo"]["latitude"], "longitude": o["geo"]["longitude"]}
    row["containedInPlace"] = o["containedInPlace"]["@id"]
    rows.append(row)
names = {}
for r in rows:
    for n in [r["name"]] + r.get("alternateNames", []):
        names.setdefault(n.casefold(), set()).add(r["id"])
errors += [f"the name {n!r} is on more than one facility" for n, ids in names.items() if len(ids) > 1]
if errors:
    sys.exit("\n".join(errors))
rows.sort(key=lambda r: r["name"].casefold())
doc = {
    "schemaVersion": "1.0.0",
    "title": "Facilities in Marin County and who runs them",
    "generated": "Generated by build_facility_list.py from output/facilities.jsonld. Do not edit.",
    "facilities": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/facilities.json is out of date. Run: python3 build_facility_list.py")
    print(f"ok: organizations/facilities.json is current ({len(rows)} facilities)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} facilities")
