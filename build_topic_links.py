#!/usr/bin/env python3
"""Write organizations/topics.json: which topic each Marin Mentions monitor is about, and how to search for it.

The link lives on the topic, as the identifier local:marin-mentions-monitor-id in output/topics.jsonld. This
file is generated from it, with the names and search hints (see place_lib.py). marin-mentions copies it. Do not
edit it by hand.

  python3 build_topic_links.py           write organizations/topics.json
  python3 build_topic_links.py   --check   fail if the file is out of date
"""
import json
import sys
from pathlib import Path

import place_lib as lib

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "organizations" / "topics.json"
graph = lib.graph("topics")
SEARCH_NAME = False  # a topic name is a subject (Fire, Economy), too generic to search for, so only its hints are searched

rows = sorted(
    ({"monitorId": m, "code": lib.code_of(o), "topic": o["@id"], "name": o["name"], "label": o["name"], "kind": "topic",
      **({} if SEARCH_NAME else {"searchName": False}), **lib.search_of(o)}
     for o in graph if o["@type"] != "DefinedTermSet" for m in lib.ident(o, lib.MONITOR_ID)),
    key=lambda r: r["monitorId"],
)
ids = [r["monitorId"] for r in rows]
if len(ids) != len(set(ids)):
    sys.exit("a monitor id is on two topics")
doc = {
    "schemaVersion": "1.0.0",
    "title": "Marin Mentions monitors and the topics they are about",
    "generated": "Generated by build_topic_links.py from output/topics.jsonld. Do not edit.",
    "topics": rows,
}
text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("organizations/topics.json is out of date. Run: python3 build_topic_links.py")
    print(f"ok: organizations/topics.json is current ({len(rows)} topics)")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} topics")
